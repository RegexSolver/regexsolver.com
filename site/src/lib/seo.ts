/**
 * SEO constants shared by the root layout and the per-page `metadata` exports.
 *
 * `SITE_URL` is the prod origin on purpose, including on the dev deploy: the
 * canonical it produces there points at prod, which is what keeps
 * dev.regexsolver.com from competing with the real site in the index.
 */

export const SITE_URL = "https://regexsolver.com";

export const SITE_NAME = "RegexSolver";

/**
 * The indexing switch: only the build whose NEXT_PUBLIC_SITE_URL is the prod
 * origin may be indexed. The deploy workflow passes it; .env.local sets
 * localhost. Anything but prod gets `noindex, nofollow`, an empty sitemap and
 * no robots.txt sitemap line. Unset defaults to prod.
 */
export const IS_PROD_SITE =
  (process.env.NEXT_PUBLIC_SITE_URL ?? SITE_URL) === SITE_URL;

/**
 * Generated by web-shared/brand/gen_og.py and copied into public/ by the
 * prebuild sync-brand step.
 */
export const OG_IMAGE = {
  url: "/og-image.png",
  width: 1200,
  height: 630,
  alt: "RegexSolver - set algebra for regex",
  type: "image/png",
};

/**
 * BreadcrumbList structured data. This is what lets Google render the
 * `regexsolver.com › …` trail above a result's title instead of a bare URL.
 *
 * Paths carry the trailing slash the export actually serves, so the `item` URLs
 * match the page's own canonical.
 */
/**
 * Next.js does NOT deep-merge `openGraph`: a page that defines its own drops
 * every layout-level field (og:site_name, og:locale, og:type vanish from that
 * page). Every `openGraph` in a `metadata` export goes through this helper so
 * those fields are always emitted.
 */
export const og = (page: { title: string; description: string; url: string }) => ({
  ...page,
  siteName: SITE_NAME,
  locale: "en_US",
  type: "website" as const,
  images: [OG_IMAGE],
});

export const breadcrumb = (
  trail: { name: string; path: string }[],
): Record<string, unknown> => ({
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: trail.map((step, i) => ({
    "@type": "ListItem",
    position: i + 1,
    name: step.name,
    item: `${SITE_URL}${step.path}`,
  })),
});
