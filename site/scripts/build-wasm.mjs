#!/usr/bin/env node
/* Builds the live demo's engine (../wasm, regexsolver compiled to
   WebAssembly) and writes its wasm-bindgen glue to public/engine/pkg/, where
   public/engine/worker.js imports it. Needs the wasm32-unknown-unknown target
   and the wasm-bindgen CLI at the version wasm/Cargo.toml pins; runs wasm-opt
   (binaryen) too when it is installed.

   Last, it writes src/lib/engineVersion.ts (gitignored): a hash of the worker
   and the engine, which src/lib/engine.ts puts on their URLs so a deploy is
   never served from a browser's cache of the previous one. */

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const crate = join(site, "..", "wasm");
const out = join(site, "public", "engine", "pkg");
const run = (cmd, args, cwd = site) =>
  execFileSync(cmd, args, { cwd, stdio: "inherit" });

run("cargo", ["build", "--release", "--locked"], crate);
run("wasm-bindgen", [
  "--target",
  "web",
  "--no-typescript",
  "--out-dir",
  out,
  join(crate, "target", "wasm32-unknown-unknown", "release", "regexsolver_demo.wasm"),
]);

/* The features Rust enables by default on wasm32-unknown-unknown: wasm-opt
   rejects a module that uses one it was not told about. */
const WASM_FEATURES = [
  "--enable-bulk-memory",
  "--enable-nontrapping-float-to-int",
  "--enable-sign-ext",
  "--enable-mutable-globals",
  "--enable-reference-types",
  "--enable-multivalue",
];

const wasm = join(out, "regexsolver_demo_bg.wasm");
try {
  run("wasm-opt", ["-O3", ...WASM_FEATURES, wasm, "-o", wasm]);
} catch (err) {
  if (err.code !== "ENOENT") throw err;
  console.warn("build-wasm: wasm-opt not found, skipping the size pass");
}

const hash = createHash("sha256");
for (const file of [
  join(site, "public", "engine", "worker.js"),
  join(out, "regexsolver_demo.js"),
  wasm,
]) {
  hash.update(readFileSync(file));
}
writeFileSync(
  join(site, "src", "lib", "engineVersion.ts"),
  `// Generated by scripts/build-wasm.mjs: a hash of the worker and the engine.
export const ENGINE_VERSION = "${hash.digest("hex").slice(0, 12)}";
`,
);
